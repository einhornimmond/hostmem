#include "hostmem/result.h"

const char *hostmem_result_to_string(hostmem_result result) {
  static const char *messages[] = {
      [HOSTMEM_SUCCESS] = "HOSTMEM_SUCCESS",
      [HOSTMEM_WARNING_ARENA_MEMORY_NOT_RECLAIMED] = "HOSTMEM_WARNING_ARENA_MEMORY_NOT_RECLAIMED",
      [HOSTMEM_WARNING_USED_DYNAMIC_ALLOCATION_FALLBACK] =
          "HOSTMEM_WARNING_USED_DYNAMIC_ALLOCATION_FALLBACK",
      [HOSTMEM_ERROR_NOT_IMPLEMENTED_YET] = "HOSTMEM_ERROR_NOT_IMPLEMENTED_YET",
      [HOSTMEM_ERROR_NOT_INITIALIZED] = "HOSTMEM_ERROR_NOT_INITIALIZED",
      [HOSTMEM_ERROR_INVALID_PARAM] = "HOSTMEM_ERROR_INVALID_PARAM",
      [HOSTMEM_ERROR_INVALID_ENUM_TYPE] = "HOSTMEM_ERROR_INVALID_ENUM_TYPE",
      [HOSTMEM_ERROR_INVALID_STATE] = "HOSTMEM_ERROR_INVALID_STATE",
      [HOSTMEM_ERROR_NULL_POINTER] = "HOSTMEM_ERROR_NULL_POINTER",
      [HOSTMEM_ERROR_ARITHMETIC_OVERFLOW] = "HOSTMEM_ERROR_ARITHMETIC_OVERFLOW",
      [HOSTMEM_ERROR_OUT_OF_MEMORY] = "HOSTMEM_ERROR_OUT_OF_MEMORY",
      [HOSTMEM_ERROR_ARRAY_INDEX_OUT_OF_BOUNDS] = "HOSTMEM_ERROR_ARRAY_INDEX_OUT_OF_BOUNDS",
      [HOSTMEM_ERROR_RESOURCE_EXHAUSTED] = "HOSTMEM_ERROR_RESOURCE_EXHAUSTED",
      [HOSTMEM_ERROR_RESOURCE_IN_USE] = "HOSTMEM_ERROR_RESOURCE_IN_USE",
      [HOSTMEM_ERROR_DECODE_FAILED] = "HOSTMEM_ERROR_DECODE_FAILED",
      [HOSTMEM_ERROR_ENCODE_FAILED] = "HOSTMEM_ERROR_ENCODE_FAILED",
      [HOSTMEM_ERROR_DESTINATION_BUFFER_TO_SMALL] = "HOSTMEM_ERROR_DESTINATION_BUFFER_TO_SMALL",
      [HOSTMEM_ERROR_ENUM_UNHANDLED] = "HOSTMEM_ERROR_ENUM_UNHANDLED",
      [HOSTMEM_ERROR_ENUM_UNKNOWN] = "HOSTMEM_ERROR_ENUM_UNKNOWN",
  };

  if (result < 0 || result >= (int)(sizeof(messages) / sizeof(messages[0]))) {
    return "HOSTMEM_ERROR_UNKNOWN";
  }
  const char *msg = messages[result];
  return msg ? msg : "HOSTMEM_ERROR_UNKNOWN";
}
